const int32_t *const tone_table[3] = { sine_table, square_table, noise_table };
uint8_t tone = 0U; // active tone 

volatile uint32_t table_index;           
volatile uint32_t table_index_inc;       
volatile uint16_t tone_hz; 

// our audio buffer is 1024 stereo sample long.  10.6666667ms latency L and R samples are inline. L's are even indexes and R's are odd. 
#define TOTAL_FRAMES 1024
volatile int32_t audio_block[2][TOTAL_FRAMES << 1]; // double buffer
volatile uint8_t play;            // buffer we stream fromm
volatile uint8_t loading;        // buffer we load while streaming
volatile uint16_t frame;        // current stereo frame
volatile int32_t sample;       // current individual sample
volatile uint8_t L_or_R;      // 0 = left slot or 1 = right slot

// returns even sample (L mono)
int32_t pcm5242_play_sample(uint16_t i){ return audio_block[play][i * 2U]; }

// update the tone_hz based on the encoder position and calculate the index increment
uint8_t last_enc4; 
void tone_freq_update(void)
{
  if(enc4_position == last_enc4) return;

  // cool formula to track encoder to a logarithmic value between two values. below is 20hz - 20khz
  float k = (float)enc4_position / 255.0f;
  tone_hz =  (uint16_t)((float)(20 * powf(20000 / 20, k))); 

  table_index_inc = (uint32_t)((((uint64_t)tone_hz) << 32) / SAMPLE_RATE);   // increment step for this hz

  last_enc4 = enc4_position;
}

// enc4's switch cycles which table the tone is generated from (sine/square/noise)
uint8_t last_enc4_sw;
void tone_toggle(void)
{
  if (!enc4_sw_level && last_enc4_sw)
    tone = (tone + 1U) % 3U;  

  last_enc4_sw = enc4_sw_level;
}

// called at the end of every stereo frame in SPI3_IRQHandler(void)
void fill_frame(void)
{
  tone_toggle(); // toggle test tone
  tone_freq_update(); 
  table_index += table_index_inc;                // advance table index

  int32_t sample = tone_table[tone][table_index >> 24];   // top 8 bits pick the table entry
  float frame_processed[2] = { (float)sample, (float)sample }; // numbers go in fx processcast as floats
  
  audio_process(frame_processed);

  // clip the processed audio to 24-bit signed range
  if(frame_processed[0] > 8388607) frame_processed[0] = 8388607;
  if(frame_processed[0] < -8388607) frame_processed[0] = -8388607;
  if(frame_processed[1] > 8388607) frame_processed[1] = 8388607;
  if(frame_processed[1] < -8388607) frame_processed[1] = -8388607;

  // stereo frame
  audio_block[loading][frame*2]     = (int32_t)(frame_processed[0]);   // left
  audio_block[loading][frame*2 + 1] = (int32_t)(frame_processed[1]);   // right
}

//init stuff for audio clock and I2S interface
void audio_clock_init(void)
{
  RCC->CR |= (1U << 16);                       // enable high speed external oscillator
  while ((RCC->CR & RCC_CR_HSERDY) == 0U);    // wait for clk stable flag

  RCC->CCIPR5 &= ~(0b11 << 30);  // clear clk source bits
  RCC->CCIPR5 |= (1U << 31);    // hse osc set as peripheral clock

  RCC->CCIPR3 &= ~(0b111 << 6);  // clear SPI3 clk select bits
  RCC->CCIPR3 |= (1U << 8);     // set peripheral clock as SPI3 source
}

void i2s3_init(void)
{
  RCC->APB1LENR |= RCC_APB1LENR_SPI3EN;   // enable clk to SPI3
  
  SPI3->CR1 = 0U;                         // clear control register

  SPI3->I2SCFGR = 0;                       // clear all bits

  SPI3->I2SCFGR |= (1U << 0);            // set the spi to i2s mode
  SPI3->I2SCFGR |= (1U << 9);           // 32-bit data
  SPI3->I2SCFGR |= (1U << 10);         // channel length 32 bit
  SPI3->I2SCFGR |= (1U << 2);         // master tranmit mode
  SPI3->I2SCFGR |= (1U << 25);       // master clock output enabled
  
  SPI3->CR1 |= SPI_CR1_SPE;        // enable SPI peripheral
}

void pcm5242_init(void){ audio_clock_init(); i2s3_init(); HAL_Delay(5); }

void pcm5242_unmute(void){ GPIOA->ODR |= (1U << 2); } // set PA2 high

void pcm5242_mute(void){ GPIOA->ODR &= ~(1U << 2); } // set PA2 low 

void pcm5242_tone_start(void)
{
  SPI3->IER |= SPI_IER_TXPIE;        // enable tx packet interrupt

  NVIC_SetPriority(SPI3_IRQn, 5U); // TIM6 is 6
  NVIC_EnableIRQ(SPI3_IRQn);      // the ISR primes the FIFO

  play = 0U;
  loading = 1U;
  frame = 0U;   // first stereo frame
  L_or_R = 0U; // start on the left slot
  table_index = 0U;     // start at the top of the table

  audio_process_init();              

  SPI3->CR1 |= SPI_CR1_CSTART;     // master tx start
}

// isr for firing the individual samples
void SPI3_IRQHandler(void)
{
  if ((SPI3->SR & SPI_SR_TXP) == 0U) return;    // is there room in the fifo?

  sample = audio_block[play][(frame*2) + L_or_R]; // grab current sample from play buffer 

  SPI3->TXDR = (uint32_t)sample << 8; // place sample into txdr (32bit bus and our sample is 24bit)

  if (L_or_R) // enters on R slot which is the end of a stereo frame
  {
    fill_frame();                  // build the SAME frame in the loading buffer

    if (frame < TOTAL_FRAMES - 1) // increment to the next frame if possible
      frame++;
    else
    {
      // exhausted play buffer, reset frame and toggle loading for play buffer
      frame = 0U;
      play ^= 1U;
      loading ^= 1U;
    }
  }

  L_or_R ^= 1U; // toggle between 0 (L) and 1 (R)
}